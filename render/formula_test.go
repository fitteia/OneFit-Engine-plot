package render

import (
	"fmt"
	"math"
	"strings"
	"testing"
)

// TestFormulaAsGracebat: each formula on ticks 1 to 5 gives what gracebat
// labelled them (decimal, precision 4 - measured with grace-probe; see
// docs/grace-behaviour.md, "Tick label formulas"), and what gracebat
// refuses is refused.
func TestFormulaAsGracebat(t *testing.T) {
	for f, want := range map[string]string{
		"$t^2":              "1.0000 4.0000 9.0000 16.0000 25.0000",
		"-$t":               "-1.0000 -2.0000 -3.0000 -4.0000 -5.0000",
		"2-$t*3":            "-1.0000 -4.0000 -7.0000 -10.0000 -13.0000",
		"(1+$t)/2":          "1.0000 1.5000 2.0000 2.5000 3.0000",
		"sqrt($t)":          "1.0000 1.4142 1.7321 2.0000 2.2361",
		"exp($t)":           "2.7183 7.3891 20.0855 54.5982 148.4132",
		"ln($t)":            "0.0000 0.6931 1.0986 1.3863 1.6094",
		"log10($t)":         "0.0000 0.3010 0.4771 0.6021 0.6990",
		"log2($t)":          "0.0000 1.0000 1.5850 2.0000 2.3219",
		"abs(-$t)":          "1.0000 2.0000 3.0000 4.0000 5.0000",
		"sin($t)":           "0.8415 0.9093 0.1411 -0.7568 -0.9589",
		"cos($t)":           "0.5403 -0.4161 -0.9900 -0.6536 0.2837",
		"atan($t)":          "0.7854 1.1071 1.2490 1.3258 1.3734",
		"PI*$t":             "3.1416 6.2832 9.4248 12.5664 15.7080",
		"1e3/$t":            "1000.0000 500.0000 333.3333 250.0000 200.0000",
		"1000/$t+0.5":       "1000.5000 500.5000 333.8333 250.5000 200.5000",
		"mod($t,2)":         "1.0000 0.0000 1.0000 0.0000 1.0000",
		"rint($t/2)":        "0.0000 1.0000 2.0000 2.0000 2.0000",
		"$T*2":              "2.0000 4.0000 6.0000 8.0000 10.0000",
		"-$t^2":             "-1.0000 -4.0000 -9.0000 -16.0000 -25.0000",
		"2^$t^2":            "2.0000 16.0000 512.0000 65536.0000 33554432.0000",
		"$t/2/2":            "0.2500 0.5000 0.7500 1.0000 1.2500",
		"tan($t/10)":        "0.1003 0.2027 0.3093 0.4228 0.5463",
		"asin($t/10)":       "0.1002 0.2014 0.3047 0.4115 0.5236",
		"acos($t/10)":       "1.4706 1.3694 1.2661 1.1593 1.0472",
		"sinh($t)":          "1.1752 3.6269 10.0179 27.2899 74.2032",
		"cosh($t)":          "1.5431 3.7622 10.0677 27.3082 74.2099",
		"tanh($t)":          "0.7616 0.9640 0.9951 0.9993 0.9999",
		"asinh($t)":         "0.8814 1.4436 1.8184 2.0947 2.3124",
		"acosh($t)":         "0.0000 1.3170 1.7627 2.0634 2.2924",
		"atanh($t/10)":      "0.1003 0.2027 0.3095 0.4236 0.5493",
		"floor($t/2)":       "0.0000 1.0000 1.0000 2.0000 2.0000",
		"ceil($t/2)":        "1.0000 1.0000 2.0000 2.0000 3.0000",
		"sqr($t)":           "1.0000 4.0000 9.0000 16.0000 25.0000",
		"sqrt(-$t)":         "nan nan nan nan nan",
		"$t%2":              "1.0000 0.0000 1.0000 0.0000 1.0000",
		"($t>2)":            "0.0000 0.0000 1.0000 1.0000 1.0000",
		"($t<3)":            "1.0000 1.0000 0.0000 0.0000 0.0000",
		"($t>=3)":           "0.0000 0.0000 1.0000 1.0000 1.0000",
		"($t<=3)":           "1.0000 1.0000 1.0000 0.0000 0.0000",
		"($t==3)":           "0.0000 0.0000 1.0000 0.0000 0.0000",
		"($t!=3)":           "1.0000 1.0000 0.0000 1.0000 1.0000",
		"($t>1)&&($t<4)":    "0.0000 1.0000 1.0000 0.0000 0.0000",
		"($t<2)||($t>4)":    "1.0000 0.0000 0.0000 0.0000 1.0000",
		"($t>1) and ($t<4)": "0.0000 1.0000 1.0000 0.0000 0.0000",
		"($t<2) or ($t>4)":  "1.0000 0.0000 0.0000 0.0000 1.0000",
		"not ($t>2)":        "1.0000 1.0000 0.0000 0.0000 0.0000",
		"!($t>2)":           "1.0000 1.0000 0.0000 0.0000 0.0000",
		"exp(1000*$t)":      "inf inf inf inf inf",
		"2*-$t":             "-2.0000 -4.0000 -6.0000 -8.0000 -10.0000",
		"--$t":              "1.0000 2.0000 3.0000 4.0000 5.0000",
		"3 - -$t":           "4.0000 5.0000 6.0000 7.0000 8.0000",
		"mod($t,0)":         "nan nan nan nan nan",
		".5*$t":             "0.5000 1.0000 1.5000 2.0000 2.5000",
		"$t*1e-1":           "0.1000 0.2000 0.3000 0.4000 0.5000",
		"2.*$t":             "2.0000 4.0000 6.0000 8.0000 10.0000",
		"abs($t-3)":         "2.0000 1.0000 0.0000 1.0000 2.0000",
		"exp(-$t)":          "0.3679 0.1353 0.0498 0.0183 0.0067",
	} {
		fm, err := parseFormula(f)
		if err != nil {
			t.Errorf("%s: %v", f, err)
			continue
		}
		var got []string
		for v := 1.0; v <= 5; v++ {
			r, err := fm.eval(v)
			if err != nil {
				t.Errorf("%s at %g: %v", f, v, err)
			}
			switch {
			case math.IsNaN(r):
				got = append(got, "nan")
			case math.IsInf(r, 1):
				got = append(got, "inf")
			default:
				got = append(got, fmt.Sprintf("%.4f", r))
			}
		}
		if g := strings.Join(got, " "); g != want {
			t.Errorf("%s: %s, gracebat %s", f, g, want)
		}
	}
	// gracebat: a syntax error, or "Error in tick transformation formula"
	for _, f := range []string{"$t**2", "log($t)", "int(2.6*$t)", "min($t,3)", "max($t,3)", "fabs(-$t)", "e*$t", "pow($t,2)", "+$t", "x*2", "1000/((", "1/0*$t", "1/($t-$t)", "$t/0.0", "$t%0"} {
		fm, err := parseFormula(f)
		if err != nil {
			continue
		}
		failed := false
		for v := 1.0; v <= 5; v++ {
			if _, err := fm.eval(v); err != nil {
				failed = true
			}
		}
		if !failed {
			t.Errorf("%s was accepted; gracebat refuses it", f)
		}
	}
}
